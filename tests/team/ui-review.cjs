"use strict";
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { _electron } = require('playwright');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'focusbae-team-ui-'));
const output = path.resolve(__dirname, '../../test-results/team-ui');
fs.mkdirSync(output, { recursive: true });
const env = { ...process.env, FOCUSBAE_TEAM_URL: 'http://127.0.0.1:3000' };
delete env.ELECTRON_RUN_AS_NODE; delete env.NODE_OPTIONS;
(async () => {
  const app = await _electron.launch({ executablePath: require('electron'), args: [path.resolve(__dirname, 'ui-probe-entry.cjs'), `--workspace-test-profile=${profile}`], env, timeout: 30000 });
  try {
    const page = await app.firstWindow();
    page.setDefaultTimeout(15000);
    await page.getByRole('heading', { name: 'Today', exact: true }).waitFor();
    const seeded = await app.evaluate(() => global.workspaceProbe.seedTeam());
    await page.reload();
    await page.getByRole('navigation').getByRole('button', { name: 'Notes', exact: true }).click();
    await page.getByRole('navigation', { name: 'Note locations' }).waitFor();
    const navRows = await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button').evaluateAll((buttons) => buttons.map((button) => Math.round(button.getBoundingClientRect().top)));
    assert.equal(new Set(navRows).size, 1, 'workspace navigation must be one horizontal row');
    const topRow = await page.locator('.brand, .workspace-picker, .header-actions').evaluateAll(els => els.map(el => { const r = el.getBoundingClientRect(); return r.top + r.height / 2; }));
    assert.ok(Math.max(...topRow) - Math.min(...topRow) < 4, 'brand, workspace and controls share a baseline');
    await page.getByRole('button', { name: 'More page options' }).click();
    await page.getByRole('menuitem', { name: 'Pinned pages' }).waitFor();
    await page.getByRole('menuitem', { name: 'Export all notes…' }).waitFor();
    await page.keyboard.press('Escape');
    const libraryLayout = await page.locator('.note-library').evaluate((el) => ({ width: el.clientWidth, columns: getComputedStyle(el).gridTemplateColumns }));
    assert.ok(libraryLayout.width > 600 && libraryLayout.columns.split(' ').length === 2, `library should use a wide page pane: ${JSON.stringify(libraryLayout)}`);
    await page.screenshot({ path: path.join(output, 'team-library-light.png'), fullPage: true });
    await page.getByRole('button', { name: 'Acme kickoff', exact: false }).click();
    await page.getByRole('tablist', { name: 'Open pages' }).waitFor();
    assert.equal(await page.locator('.note-library').isVisible(), true, 'other notes remain available while editing');
    await page.locator('.note-row', { hasText: 'Private thinking' }).click();
    await page.getByRole('tab', { name: 'Private thinking', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Acme kickoff', exact: true }).click();
    await page.getByRole('button', { name: 'Workspace graph', exact: true }).click();
    await page.getByRole('tab', { name: 'Graph', exact: true }).waitFor();
    await page.getByRole('tab', { name: 'Acme kickoff', exact: true }).click();
    const result = await page.evaluate(async () => window.focusbaeWorkspace.folders.list({ workspaceId: (await window.focusbaeWorkspace.bootstrap()).value.workspace.id }));
    assert.equal(result.ok, true, JSON.stringify(result));
    assert.ok(result.value.items.some((f) => f.teamRoot && f.name === 'Engineering'));
    assert.ok(result.value.items.some((f) => f.name === 'Client work' && f.spaceId === '44444444-4444-4444-8444-444444444444'));
    await page.getByRole('combobox', { name: 'Folder for this page' }).waitFor();
    assert.equal(await page.getByRole('combobox', { name: 'Folder for this page' }).inputValue(), seeded.folder);
    assert.equal(await page.getByRole('combobox', { name: 'Note view' }).count(), 0);
    assert.equal(await page.getByRole('menu', { name: 'Page options', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Page options', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Show connections' }).waitFor();
    await page.getByRole('menuitem', { name: 'Move to Trash' }).waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('menu', { name: 'Page options', exact: true }).count(), 0);
    await page.screenshot({ path: path.join(output, 'team-notebook-light.png'), fullPage: true });
    await page.getByRole('button', { name: 'Browse folders', exact: true }).click();
    await page.getByRole('button', { name: 'New folder', exact: true }).waitFor();
    const locations = page.getByRole('navigation', { name: 'Note locations' });
    await locations.getByRole('button', { name: 'Expand Engineering' }).click();
    await locations.getByRole('button', { name: /Client work/ }).click();
    await page.locator('.note-row', { hasText: 'Acme kickoff' }).waitFor();
    await page.locator('.note-row', { hasText: 'Private thinking' }).waitFor({ state: 'hidden' });
    await page.locator('.note-row', { hasText: 'Acme kickoff' }).click();
    await page.getByRole('button', { name: 'Browse folders', exact: true }).click();
    await locations.getByRole('button', { name: 'Collapse Engineering' }).waitFor();
    assert.equal(await page.locator('.note-row', { hasText: 'Private thinking' }).count(), 0);
    await locations.getByRole('button', { name: 'Collapse Engineering' }).click();
    assert.equal(await locations.getByRole('button', { name: /Client work/ }).count(), 0);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    const teamHeading = page.getByRole('heading', { name: 'Team workspaces' });
    await teamHeading.waitFor();
    await teamHeading.scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'team-settings-light.png'), fullPage: true });
    await page.getByRole('navigation').getByRole('button', { name: 'Notes', exact: true }).click();
    await page.getByRole('button', { name: 'Acme kickoff', exact: false }).click();
    await page.locator('.note-row', { hasText: 'Pricing decision' }).click();
    await page.getByText("Priya's page · Engineering").waitFor();
    assert.equal(await page.getByRole('toolbar', { name: 'Text formatting' }).count(), 0, "a teammate's page has no formatting tools");
    assert.equal(await page.getByRole('textbox', { name: 'Note title' }).getAttribute('readonly'), '');
    assert.equal(await page.locator('.ProseMirror').last().getAttribute('contenteditable'), 'false');
    const locked = page.locator('.link-chip.restricted', { hasText: 'Board salaries' });
    await locked.waitFor();
    assert.equal(await page.locator('.link-chip', { hasText: 'create' }).count(), 0, "a teammate's link never offers to create a page");
    await locked.click();
    await page.getByText('Restricted page: you can\'t open "Board salaries"', { exact: false }).waitFor();
    assert.equal(await page.locator('.note-row', { hasText: 'Board salaries' }).count(), 1, 'no page was created; the one row is the teammate page itself');
    await page.getByRole('button', { name: 'Page options', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Show connections' }).waitFor();
    assert.equal(await page.getByRole('menuitem', { name: 'Move to Trash' }).count(), 0);
    await page.keyboard.press('Escape');
    await page.screenshot({ path: path.join(output, 'team-teammate-page-light.png'), fullPage: true });
    await page.getByRole('navigation').getByRole('button', { name: 'People', exact: true }).click();
    await page.getByRole('button', { name: /Priya.*on the team ledger/ }).click();
    await page.getByRole('heading', { name: 'Priya owes, on the team ledger' }).waitFor();
    await page.getByText('Share the revised plan', { exact: true }).waitFor();
    await page.getByRole('heading', { name: 'Pages that mention Priya' }).waitFor();
    await page.getByRole('button', { name: 'Open Acme kickoff' }).waitFor();
    await page.screenshot({ path: path.join(output, 'team-person-light.png'), fullPage: true });
    await page.getByRole('button', { name: 'Open Acme kickoff' }).click();
    await page.getByRole('tab', { name: 'Acme kickoff', exact: true }).waitFor();
    // A focusbae://team/connect link opens Settings with the next step pointed out.
    await app.evaluate(() => global.workspaceProbe.openCommand('team-connect', { workspace: '99999999-9999-4999-8999-999999999999' }));
    await page.getByRole('heading', { name: 'Team workspaces' }).waitFor();
    await page.locator('.team-link-banner').waitFor();
    assert.ok(await page.locator('.team-link-banner').isVisible(), 'the banner is scrolled into view');
    await page.waitForTimeout(300);
    await page.screenshot({ path: path.join(output, 'team-link-light.png') });
    await page.getByRole('navigation').getByRole('button', { name: 'People', exact: true }).click();
    await page.getByRole('button', { name: 'Record', exact: true }).click();
    await page.getByText('Saving to', { exact: false }).waitFor();
    assert.match(await page.locator('.record-destination').textContent(), /team workspace/);
    await page.screenshot({ path: path.join(output, 'team-record-light.png'), fullPage: true });
    await page.getByRole('button', { name: 'Close recording dialog' }).click();
    await page.getByRole('navigation').getByRole('button', { name: 'Notes', exact: true }).click();
    await app.evaluate(() => global.workspaceProbe.seedManyFolders());
    await page.reload();
    await page.getByRole('navigation').getByRole('button', { name: 'Notes', exact: true }).click();
    await page.getByRole('navigation', { name: 'Note locations' }).getByRole('button', { name: 'Expand Engineering' }).click();
    const treeSize = await page.locator('.library-locations').evaluate((el) => ({ viewport: el.clientHeight, content: el.scrollHeight }));
    assert.ok(treeSize.content > treeSize.viewport, `many folders must scroll in the folder rail: ${JSON.stringify(treeSize)}`);
    const listHeight = await page.locator('.note-rows').evaluate((el) => el.clientHeight);
    assert.ok(listHeight > 160, `page list retains space with many folders: ${listHeight}px`);
    await page.screenshot({ path: path.join(output, 'team-folders-many.png'), fullPage: true });
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.waitForTimeout(220);
    await page.screenshot({ path: path.join(output, 'team-folders-dark.png'), fullPage: true });
    const darkColors = await page.locator('.library-quick-views button[aria-current="page"]').evaluate((el) => ({ background: getComputedStyle(el).backgroundColor, foreground: getComputedStyle(el).color }));
    assert.notEqual(darkColors.background, 'rgb(226, 233, 215)', `dark selection must use a dark surface: ${JSON.stringify(darkColors)}`);
    const darkRow = await page.locator('.note-row').first().evaluate((el) => getComputedStyle(el).backgroundColor);
    assert.ok(Number(darkRow.match(/\d+/)?.[0]) < 100, `dark page rows must have a dark surface: ${darkRow}`);
    await page.setViewportSize({ width: 710, height: 760 });
    assert.equal(await page.getByRole('combobox', { name: 'Workspace', exact: true }).isVisible(), true);
    await page.screenshot({ path: path.join(output, 'team-notebook-narrow.png'), fullPage: true });
    console.log(`PASS: compact team folder browser, one page location picker and team settings. Screenshots: ${output}`);
  } finally { await app.close(); fs.rmSync(profile, { recursive: true, force: true }); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
